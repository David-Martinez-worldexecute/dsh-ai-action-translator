#!/usr/bin/env node
/**
 * 多宿主适配层生成器。
 *
 * 输入只有两样：`adapters/_core/policy.json`（来自 lib/guard.js）和 `adapters/_core/prompt.mjs`。
 * 输出是四套「可以直接复制进项目根」的目录。
 *
 * 为什么是生成而不是手写四份：
 *   四份手写的配置，只要有一份忘了跟着改，用户拿到的就是「装了但没生效」，
 *   而那种状态最难发现 —— 界面在、文件也在，就是不拦。
 *
 * 产物都带 GENERATED 头注释；`--check` 用同输入重算一遍并逐字节比对，防漂移。
 *
 * 用法：
 *   node tools/build-adapters.mjs           # 生成
 *   node tools/build-adapters.mjs --check   # 只比对
 */
