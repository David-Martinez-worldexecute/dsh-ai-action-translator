#!/usr/bin/env node
/**
 * 把 lib/guard.js 的守门规则导出成 adapters/_core/policy.json。
 *
 * 为什么要这么一个「只导出」的脚本，而不是手工写一份 policy.json：
 *   手抄的规则会漂。改了 lib/guard.js 里某条正则，却忘了改 adapter 那份，
 *   两处就开始说不同的话 —— 而这种不一致在测试里是绿的、在用户那儿是真放行。
 *   所以 poliy.json 只当产物，真源永远只有 GUARD_RULES 一处。
 *
 * 用法：
 *   node tools/build-policy.mjs            # 重写 adapters/_core/policy.json
 *   node tools/build-policy.mjs --check    # 只比对，不一致就退出 1（CI / 测试用）
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { GUARD_LEVELS, GUARD_MODES, GUARD_RULES, GUARD_SKIP_TOOLS } from '../lib/guard.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const OUT = path.join(ROOT, 'adapters', '_core', 'policy.json')

const NOTE = 'GENERATED by tools/build-policy.mjs from lib/guard.js — 不要手改。'

/**
 * 规则里的正则不能直接 JSON.stringify（会变成空对象 `{}`），
 * 所以拆成 source + flags 两个字符串，判定时再 `new RegExp(source, flags)` 拼回去。
 * 其余字段原样展开：`alwaysCheck` / `quiet` / `always` / `tools` 这些语义位
 * 一个都不能丢，丢了就等于悄悄放宽了守门。
 */
export function buildPolicy() {
  return {
    $comment: NOTE,
    schema: 1,
    modes: [...GUARD_MODES],
    levels: [...GUARD_LEVELS],
    // 「只读工具」名单：这些工具上不套用大部分规则（凭据类例外，靠 alwaysCheck）。
    // 放在这里而不是让每个 adapter 手抄一份，理由和规则本身一样——抄两份就会漂。
    skipTools: [...GUARD_SKIP_TOOLS],
    rules: GUARD_RULES.map((rule) => ({
      ...rule,
      patterns: rule.patterns.map((pattern) => ({ source: pattern.source, flags: pattern.flags })),
    })),
  }
}

/** 稳定的序列化：同输入必得同字节，方便 --check 与幂等校验。 */
export function serializePolicy(policy) {
  return `${JSON.stringify(policy, null, 2)}\n`
}

function main(argv) {
  const check = argv.includes('--check')
  const wanted = serializePolicy(buildPolicy())
  const exists = fs.existsSync(OUT)
  const current = exists ? fs.readFileSync(OUT, 'utf8') : ''

  if (check) {
    if (!exists) {
      console.error(`POLICY_MISSING ${OUT}`)
      return 1
    }
    if (current !== wanted) {
      console.error('POLICY_DRIFT policy.json 与 lib/guard.js 不一致，跑 node tools/build-policy.mjs 重新生成')
      return 1
    }
    console.log(`POLICY_OK rules=${buildPolicy().rules.length}`)
    return 0
  }

  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, wanted)
  const written = JSON.parse(fs.readFileSync(OUT, 'utf8'))
  console.log(`POLICY_WRITTEN ${path.relative(ROOT, OUT)} rules=${written.rules.length}`)
  return 0
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  process.exitCode = main(process.argv.slice(2))
}
